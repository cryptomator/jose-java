package org.cryptomator.jose;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;

import java.util.Objects;

/// A recipient of a Key Encryption JWE: the algorithm protecting the content encryption key for this recipient plus caller-supplied
/// per-recipient header parameters (e.g. `kid`), see [RFC 7516, Section 7.2.1](https://www.rfc-editor.org/rfc/rfc7516#section-7.2.1).
/// Create one with [#withAlg] and refine it with [#withClaim] / [#withClaims]; every step returns a complete, immutable recipient.
///
/// The caller header must not contain parameters the algorithm generates itself ([KeyEncryptionAlg#generatedHeaderParams], e.g. `alg`, `epk`, `ek`,
/// `p2s`, `p2c`); such a claim is rejected immediately with an [IllegalArgumentException]. Collisions with the protected or shared unprotected
/// header can only be detected when encrypting and are rejected there, likewise with an [IllegalArgumentException] naming the parameter and the
/// two locations (nothing is silently overwritten). For a single recipient in compact serialization, the header is folded into the protected header.
///
/// @param alg The algorithm encrypting the content encryption key for this recipient
/// @param header Per-recipient header parameters supplied by the caller (never `null`; copied on construction)
public record Recipient(KeyEncryptionAlg alg, JsonObject header) {

	/// @throws IllegalArgumentException if the header contains a parameter the algorithm generates itself
	public Recipient {
		Objects.requireNonNull(alg, "alg");
		header = header == null ? new JsonObject() : header.deepCopy();
		var generated = alg.generatedHeaderParams();
		var claimCollision = header.keySet().stream().filter(generated::contains).findFirst();
		if (claimCollision.isPresent()) {
			throw new IllegalArgumentException("Header parameter '" + claimCollision.get() + "' is generated by " + alg.name() + " and must not be supplied by the caller");
		}
	}

	/// @param alg The algorithm encrypting the content encryption key for this recipient
	/// @return A recipient without caller-supplied header parameters
	public static Recipient withAlg(KeyEncryptionAlg alg) {
		return new Recipient(alg, new JsonObject());
	}

	/// @param header Per-recipient header parameters replacing all current ones
	/// @return A copy of this recipient with the given header
	/// @throws IllegalArgumentException if the header contains a parameter the algorithm generates itself (see [KeyEncryptionAlg#generatedHeaderParams])
	public Recipient withClaims(JsonObject header) throws IllegalArgumentException {
		return new Recipient(alg, header);
	}

	/// @param name The header parameter name, e.g. `kid`
	/// @param value The header parameter value
	/// @return A copy of this recipient with the given header parameter added (or replaced, if already present)
	/// @throws IllegalArgumentException if the algorithm generates the named parameter itself (see [KeyEncryptionAlg#generatedHeaderParams])
	public Recipient withClaim(String name, JsonElement value) throws IllegalArgumentException {
		var headers = header();
		headers.add(Objects.requireNonNull(name, "name"), Objects.requireNonNull(value, "value"));
		return withClaims(headers);
	}

	/// @param name The header parameter name, e.g. `kid`
	/// @param value The header parameter value
	/// @return A copy of this recipient with the given string header parameter added (or replaced, if already present)
	/// @throws IllegalArgumentException if the algorithm generates the named parameter itself (see [KeyEncryptionAlg#generatedHeaderParams])
	public Recipient withClaim(String name, String value) throws IllegalArgumentException {
		return withClaim(name, new JsonPrimitive(Objects.requireNonNull(value, "value")));
	}

	/// @param name The header parameter name, e.g. `org.example.iterations`
	/// @param value The header parameter value
	/// @return A copy of this recipient with the given numeric header parameter added (or replaced, if already present)
	/// @throws IllegalArgumentException if the algorithm generates the named parameter itself (see [KeyEncryptionAlg#generatedHeaderParams])
	public Recipient withClaim(String name, Number value) throws IllegalArgumentException {
		return withClaim(name, new JsonPrimitive(Objects.requireNonNull(value, "value")));
	}

	/// @param name The header parameter name
	/// @param value The header parameter value
	/// @return A copy of this recipient with the given boolean header parameter added (or replaced, if already present)
	/// @throws IllegalArgumentException if the algorithm generates the named parameter itself (see [KeyEncryptionAlg#generatedHeaderParams])
	public Recipient withClaim(String name, boolean value) throws IllegalArgumentException {
		return withClaim(name, new JsonPrimitive(value));
	}

	@Override
	public JsonObject header() {
		return header.deepCopy();
	}

}
