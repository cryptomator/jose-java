package org.cryptomator.jose.alg;

import com.google.gson.JsonObject;
import org.cryptomator.jose.JoseDecryptException;
import org.cryptomator.jose.JoseParseException;
import org.cryptomator.jose.util.Curve;
import org.cryptomator.jose.util.Destroyables;
import org.cryptomator.jose.util.ECHelper;

import javax.crypto.KeyAgreement;
import javax.crypto.spec.SecretKeySpec;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.InvalidKeyException;
import java.security.NoSuchAlgorithmException;
import java.security.interfaces.ECPrivateKey;
import java.security.interfaces.ECPublicKey;
import java.util.Arrays;
import java.util.Base64;

public final class EcdhEsAlg extends AbstractKeyAlg {

	private static final String EC_ALG = "EC";

	public enum Type {
		ECDH_ES_A256KW("ECDH-ES+A256KW", "AES", 32),
		;

		private final String jwaAlgName;
		private final String jcaKeyAlgName;
		private final int keyLength;

		Type(String jwaAlgName, String jcaKeyAlgName, int keyLength) {
			this.jwaAlgName = jwaAlgName;
			this.jcaKeyAlgName = jcaKeyAlgName;
			this.keyLength = keyLength;
		}
	}

	private final Type type;
	private final Curve curve;
	private final ECPublicKey publicKey;
	private final ECPrivateKey privateKey;

	public EcdhEsAlg(Type type, Curve curve, ECPublicKey publicKey, ECPrivateKey privateKey) {
		this.type = type;
		this.curve = curve;
		this.publicKey = publicKey == null ? null : ECHelper.validateKey(publicKey, curve.getCurveParams());
		this.privateKey = privateKey;
	}

	@Override
	public String name() {
		return "ECDH-ES+A256KW";
	}

	@Override
	protected byte[] decryptKey(JsonObject combinedHeader, byte[] encryptedKey) throws JoseDecryptException {
		if (privateKey == null) {
			throw new IllegalStateException("No private key available for decryption.");
		}

		// import ephemeral public key:
		if (!combinedHeader.has("epk") || !combinedHeader.get("epk").isJsonObject()) {
			throw new DecryptKeyException("Missing or non-object 'epk' header");
		}
		ECPublicKey epk;
		try {
			var key = ECHelper.fromJwk(combinedHeader.getAsJsonObject("epk"));
			if (key instanceof ECPublicKey k) {
				epk = k;
			} else {
				throw new DecryptKeyException("Ephemeral key is not an EC public key");
			}
		} catch (JoseParseException e) {
			throw new DecryptKeyException("Invalid 'epk'", e);
		}
		if (Curve.valueOf(epk.getParams().getCurve()) != curve) {
			throw new DecryptKeyException("'epk' is not on the recipient key's curve"); // e.g. a multi-recipient JWE whose other recipients use different curves
		}

		// derive shared secret using ECDH-ES:
		final byte[] sharedSecret;
		try {
			sharedSecret = ecdh(epk, privateKey);
		} catch (InvalidKeyException e) {
			throw new DecryptKeyException("Unsuitable key for ECDH", e);
		}

		// derive wrapping key using KDF:
		final byte[] wrappingKeyBytes;
		try {
			wrappingKeyBytes = deriveKey(sharedSecret, combinedHeader);
		} finally {
			Arrays.fill(sharedSecret, (byte) 0x00);
		}

		// unwrap using AES key wrap:
		try {
			return AesKw.unwrap(new SecretKeySpec(wrappingKeyBytes, type.jcaKeyAlgName), encryptedKey);
		} finally {
			Arrays.fill(wrappingKeyBytes, (byte) 0x00);
		}
	}

	@Override
	public EncryptionResult encrypt(JsonObject combinedHeader, byte[] cek) {
		if (publicKey == null) {
			throw new IllegalStateException("No public key available for encryption.");
		}

		// generate ephemeral key pair:
		var keyPair = curve.generateKeyPair();
		final ECPrivateKey ephPrivateKey;
		final ECPublicKey ephPublicKey;
		if (keyPair.getPrivate() instanceof ECPrivateKey priv
				&& keyPair.getPublic() instanceof ECPublicKey pub) {
			ephPrivateKey = priv;
			ephPublicKey = pub;
		} else {
			throw new AssertionError("Key generated by EC key generator not an EC key");
		}

		// derive shared secret using ECDH-ES:
		final byte[] sharedSecret;
		try {
			sharedSecret = ecdh(publicKey, ephPrivateKey);
		} catch (InvalidKeyException e) {
			throw new IllegalStateException("Unsuitable key for ECDH", e); // the recipient key was validated against the curve in the constructor
		} finally {
			Destroyables.destroyQuietly(ephPrivateKey);
		}

		// derive wrapping key using KDF:
		final byte[] wrappingKeyBytes;
		try {
			wrappingKeyBytes = deriveKey(sharedSecret, combinedHeader);
		} finally {
			Arrays.fill(sharedSecret, (byte) 0x00);
		}

		// wrap using AES key wrap:
		final byte[] encryptedKey;
		try {
			encryptedKey = AesKw.wrap(new SecretKeySpec(wrappingKeyBytes, type.jcaKeyAlgName), cek);
		} finally {
			Arrays.fill(wrappingKeyBytes, (byte) 0x00);
		}

		// assemble header
		JsonObject perRecipientHeader = new JsonObject();
		perRecipientHeader.addProperty("alg", type.jwaAlgName);
		perRecipientHeader.add("epk", ECHelper.toJwk(ephPublicKey));
//		perRecipientHeader.addProperty("apu", combinedHeader.get("apu").getAsString());
//		perRecipientHeader.addProperty("apv", combinedHeader.get("apv").getAsString());
		return new EncryptionResult(encryptedKey, perRecipientHeader);
	}

	private byte[] ecdh(ECPublicKey publicKey, ECPrivateKey privateKey) throws InvalidKeyException {
		try {
			var keyAgreement = KeyAgreement.getInstance("ECDH");
			keyAgreement.init(privateKey);
			keyAgreement.doPhase(publicKey, true);
			return keyAgreement.generateSecret();
		} catch (NoSuchAlgorithmException e) {
			throw new UnsupportedOperationException("JVM does not support ECDH", e);
		}
	}

	// visible for testing (org.cryptomator.jose.alg is not an exported package, so this is not public API): lets EcdhEsAlgTest verify apu/apv are wired into the ConcatKDF OtherInfo
	public byte[] deriveKey(byte[] sharedSecret, JsonObject combinedHeader) {
		var algorithmId = type.jwaAlgName.getBytes(StandardCharsets.US_ASCII); // TODO: if alg is "ECDH-ES" (without key wrap), use "enc" value from header
		var partyUInfo = combinedHeader.has("apu") ? Base64.getUrlDecoder().decode(combinedHeader.get("apu").getAsString()) : new byte[0];
		var partyVInfo = combinedHeader.has("apv") ? Base64.getUrlDecoder().decode(combinedHeader.get("apv").getAsString()) : new byte[0];
		var suppPubInfo = type.keyLength * Byte.SIZE; // keydatalen in bits, see RFC 7518 Section 4.6.2
		var suppPrivInfo = new byte[0];
		ByteBuffer otherInfo = ByteBuffer.allocate(Integer.BYTES + algorithmId.length
				+ Integer.BYTES + partyUInfo.length
				+ Integer.BYTES + partyVInfo.length
				+ Integer.BYTES
				+ suppPrivInfo.length
		);
		otherInfo.putInt(algorithmId.length).put(algorithmId);
		otherInfo.putInt(partyUInfo.length).put(partyUInfo);
		otherInfo.putInt(partyVInfo.length).put(partyVInfo);
		otherInfo.putInt(suppPubInfo);
		otherInfo.put(suppPrivInfo);
		return ConcatKDF.sha256().kdf(sharedSecret, type.keyLength, otherInfo.array());
	}

}
